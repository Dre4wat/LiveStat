// Browser-side PNG card renderer. Real values only; ESPN photos proxy through same origin.
export async function exportPlayerCard({player={},sport='nba',season,game=null,metrics=[],theme='redline',title='GAME PERFORMANCE',filename='livestat-card'}){
  if(typeof document==='undefined')throw Error('Card export requires a browser');
  const canvas=document.createElement('canvas');canvas.width=1080;canvas.height=1350;
  const c=canvas.getContext('2d');if(!c)throw Error('Canvas not available');
  const themes={
    redline:{bg:'#08090d',panel:'#1c121b',accent:'#e72e48'},
    silver:{bg:'#101218',panel:'#222832',accent:'#dfe6ef'},
    midnight:{bg:'#040e17',panel:'#0d283e',accent:'#52c1ff'}
  };
  const t=themes[theme]||themes.redline;
  const teamHex=/^[0-9a-f]{6}$/i.test(String(player.teamColor||''))?'#'+player.teamColor:t.accent;
  const bg=c.createLinearGradient(0,0,1080,1350);bg.addColorStop(0,t.bg);bg.addColorStop(.6,t.panel);bg.addColorStop(1,t.bg);c.fillStyle=bg;c.fillRect(0,0,1080,1350);
  c.fillStyle=teamHex;c.fillRect(0,0,17,1350);c.fillRect(0,0,1080,15);
  c.fillStyle='#fff';c.font='bold 55px Arial';c.fillText('LIVE',70,107);
  c.fillStyle=t.accent;c.fillText('STAT',208,107);
  c.font='bold 22px Arial';c.fillStyle='#c1c0c8';c.fillText('ANALYTICS LAB   /   PLAYER CARD STUDIO',70,150);
  c.textAlign='right';c.fillStyle='#fff';c.font='bold 25px Arial';c.fillText(String(sport).toUpperCase()+'  ·  '+String(season||''),1010,105);c.textAlign='left';
  c.fillStyle=t.accent;c.fillRect(70,195,940,7);
  let photoLoaded=false;
  const imgUrl=String(player.headshot||'');
  if(/^https:\/\/(?:a\.espncdn\.com|a1\.espncdn\.com|a2\.espncdn\.com|a\.espn\.com)\/i\/headshots\//i.test(imgUrl)){
    try{
      const photo=new Image();
      await new Promise((resolve,reject)=>{
        photo.onload=resolve;photo.onerror=reject;
        photo.src='/api/analytics/headshot?url='+encodeURIComponent(imgUrl);
      });
      const ratio=photo.width/photo.height;
      const maxWidth=790,maxHeight=635;
      const h=Math.min(maxHeight,maxWidth/ratio),w=h*ratio;
      c.drawImage(photo,1080-w-75,240,w,h);photoLoaded=true;
    }catch{}
  }
  if(!photoLoaded){
    c.strokeStyle='#9f344b';c.lineWidth=12;c.beginPath();c.arc(780,480,150,0,Math.PI*2);c.stroke();
    c.font='bold 112px Arial';c.fillStyle='#513340';c.textAlign='center';
    c.fillText(String(player.name||'PLAYER').split(/\s+/).slice(0,2).map(x=>x[0]||'').join('').toUpperCase(),780,522);c.textAlign='left';
  }
  const first=String(player.name||'PLAYER').split(' '),last=first.length>1?first.pop():'';
  c.font='bold 47px Arial';c.fillStyle='#fff';c.fillText(first.join(' ').toUpperCase().slice(0,19),70,710);
  c.font='bold 93px Arial';c.fillStyle=t.accent;c.fillText((last||first[0]||'ATHLETE').toUpperCase().slice(0,13),70,805);
  c.fillStyle='#d9c9cf';c.font='bold 26px Arial';c.fillText(String(player.team||'').toUpperCase().slice(0,40)+'   '+String(player.position||'').toUpperCase(),73,858);
  c.fillStyle='#fff';c.font='bold 25px Arial';c.fillText(String(title||'PERFORMANCE').toUpperCase().slice(0,55),70,955);
  const clean=metrics.slice(0,4);
  const boxWidth=(940-30*(clean.length-1))/Math.max(1,clean.length);
  for(let i=0;i<clean.length;i++){
    const x=70+i*(boxWidth+30),item=clean[i];
    c.fillStyle='#25232a';c.fillRect(x,982,boxWidth,185);
    c.fillStyle=t.accent;c.fillRect(x,982,boxWidth,5);
    c.fillStyle='#fff';c.font='bold 60px Arial';c.textAlign='center';
    c.fillText(item.value==null?'—':String(item.value).slice(0,8),x+boxWidth/2,1083);
    c.fillStyle='#c8b8bf';c.font='bold 21px Arial';c.fillText(String(item.label||'STAT').toUpperCase().slice(0,14),x+boxWidth/2,1132);c.textAlign='left';
  }
  c.fillStyle='#a39ca4';c.font='22px Arial';c.fillText('Data: ESPN unofficial · Recorded stats only · Generated by LiveStat',70,1232);
  c.fillStyle=t.accent;c.fillRect(70,1260,940,3);
  c.fillStyle='#fff';c.font='bold 22px Arial';c.fillText('REAL GAMES. REAL MOMENTS.',70,1304);
  c.textAlign='right';c.fillStyle='#c2a7b1';c.fillText('LIVESTAT',1010,1304);
  const blob=await new Promise(resolve=>canvas.toBlob(resolve,'image/png'));
  if(!blob)throw Error('PNG creation failed');
  const url=URL.createObjectURL(blob),a=document.createElement('a');
  a.href=url;a.download=filename.replace(/[^a-z0-9-_]/gi,'-').slice(0,65)+'.png';
  document.body.appendChild(a);a.click();a.remove();
  setTimeout(()=>URL.revokeObjectURL(url),15000);
  return {width:1080,height:1350};
}
